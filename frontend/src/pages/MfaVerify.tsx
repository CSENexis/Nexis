import React, { useState, useEffect } from 'react';
import { Link, useNavigate } from 'react-router-dom';
import { api, NexisApiError, UserMe } from '../lib/api';
import { setPageFocus, focusFirstError } from '../lib/focus';
import { announce } from '../a11y/announcements';
import { CodeInput } from '../components/CodeInput';
import { ErrorSummary } from '../components/ErrorSummary';

interface MfaVerifyProps {
  onVerificationSuccess: (user: UserMe) => void;
}

export const MfaVerify: React.FC<MfaVerifyProps> = ({ onVerificationSuccess }) => {
  const [code, setCode] = useState('');
  const [errors, setErrors] = useState<string[]>([]);
  const [codeError, setCodeError] = useState<string | undefined>(undefined);
  const [loading, setLoading] = useState(false);
  const navigate = useNavigate();

  useEffect(() => {
    setPageFocus('Two-Step Verification');
  }, []);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setErrors([]);
    setCodeError(undefined);

    const cleanCode = code.replace(/\s+/g, '');
    if (!cleanCode || cleanCode.length < 6) {
      const err = 'Please enter all 6 digits of your verification code.';
      setCodeError(err);
      setErrors([err]);
      focusFirstError();
      announce(err, 'assertive');
      return;
    }

    setLoading(true);
    try {
      await api.mfa.verify(cleanCode);
      announce('Verification successful. Access granted to your dashboard.', 'polite');
      const me = await api.auth.me();
      onVerificationSuccess(me);
      navigate('/dashboard');
    } catch (err) {
      const apiErr = err as NexisApiError;
      setErrors([apiErr.message]);
      setCodeError(apiErr.message);
      focusFirstError();
      announce(`Verification failed: ${apiErr.message}`, 'assertive');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="max-w-md mx-auto my-10 p-6 bg-white border border-slate-300 rounded-xl shadow-md">
      <h1 className="text-2xl font-bold text-slate-900 mb-2 focus:outline-none">
        Two-Step Verification
      </h1>
      <p className="text-sm text-slate-600 mb-6">
        Your password has been verified. Enter the 6-digit one-time code generated by your authenticator application.
      </p>

      <ErrorSummary errors={errors} />

      <form onSubmit={handleSubmit} noValidate>
        <CodeInput
          id="totp-verify-input"
          value={code}
          onChange={setCode}
          error={codeError}
          disabled={loading}
        />

        <button
          type="submit"
          disabled={loading}
          className="w-full py-3 px-4 bg-blue-700 hover:bg-blue-800 text-white font-semibold rounded-md shadow-sm focus:outline-none focus:ring-4 focus:ring-blue-600 focus:ring-offset-2 transition-colors disabled:opacity-50 text-base"
        >
          {loading ? 'Verifying Code...' : 'Verify Code & Sign In'}
        </button>

        <div className="mt-6 border-t border-slate-200 pt-4 text-sm text-slate-600 text-left">
          <p className="mb-2 font-medium text-slate-800">
            Cannot access your authenticator application?
          </p>
          <Link
            to="/recover"
            className="text-blue-700 font-semibold hover:underline focus:outline-none focus:ring-2 focus:ring-blue-600 rounded inline-block"
          >
            Use a one-time recovery code to access your account
          </Link>
        </div>
      </form>
    </div>
  );
};
